function tl(obj, field) {
  if (!obj) return '';
  const thKey = field + 'Th';
  return (lang === 'th' && obj[thKey]) ? obj[thKey] : (obj[field] ?? '');
}
function setLang(l) {
  if (!I18N_LANGS.includes(l)) return;
  lang = l;
  try { localStorage.setItem('aerd_lang', l); } catch (e) {}
  if (typeof document !== 'undefined' && document.documentElement) document.documentElement.lang = l;
  applyI18n();
  if (typeof window !== 'undefined' && window.Game && window.Game.onLangChange) window.Game.onLangChange();
}
function applyI18n() {
  if (typeof document === 'undefined' || !document.querySelectorAll) return;
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  document.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = t(el.dataset.i18nPlaceholder); });
}
